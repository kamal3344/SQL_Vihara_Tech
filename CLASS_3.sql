/* JOINS */

INNER_JOIN:

SELECT *FROM EMPLOYEE_DETAILS INNER JOIN STUDENT_DETAILS ON EMPLOYEE_DETAILS.EMPID=STUDENT_DETAILS.STDID

LEFT_OUTER_JOIN:
SELECT *FROM EMPLOYEE_DETAILS LEFT OUTER JOIN STUDENT_DETAILS ON EMPLOYEE_DETAILS.EMPID=STUDENT_DETAILS.STDID


RIGHT_OUTER_JOIN:
SELECT *FROM EMPLOYEE_DETAILS RIGHT OUTER JOIN STUDENT_DETAILS ON EMPLOYEE_DETAILS.EMPID=STUDENT_DETAILS.STDID


FULL_OUTER_JOIN:
SELECT *FROM EMPLOYEE_DETAILS FULL OUTER JOIN STUDENT_DETAILS ON EMPLOYEE_DETAILS.EMPID=STUDENT_DETAILS.STDID


CROSS_JOIN:
SELECT *FROM EMPLOYEE_DETAILS CROSS JOIN STUDENT_DETAILS


EQUI_JOIN:

SELECT *FROM EMPLOYEE_DETAILS,STUDENT_DETAILS WHERE EMPLOYEE_DETAILS.EMPID=STUDENT_DETAILS.STDID

NON_EQUI_JOIN:

SELECT *FROM EMPLOYEE_DETAILS,STUDENT_DETAILS WHERE EMPLOYEE_DETAILS.EMPID>STUDENT_DETAILS.STDID